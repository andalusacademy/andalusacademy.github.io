-- 1) تأكد الأول إن محدش جاوب على سؤال النهاردة اللي اتحط بالباكفيل (لو النتيجة مش فاضية، بلّغني
--    قبل ما تكمل، عشان مسح السؤال هيخلي إجابته القديمة تتقارن بسؤال تاني)
SELECT * FROM daily_quiz_answers WHERE quiz_date = CURRENT_DATE;

-- 2) لو النتيجة فوق فاضية (محدش جاوب لسه)، امسح سؤال النهاردة المؤقت
DELETE FROM daily_quiz_schedule WHERE quiz_date = CURRENT_DATE;

-- 3) مهمة كرون لمرة واحدة الليلة بس الساعة 10 مساءً بتوقيت مصر (20:00 UTC) — بتفعّل سؤال جديد للنهاردة
--    من غير ما تلمس جدولة الـ7 مساءً العادية، فبكرة وكل الأيام الجايه هترجع تشتغل الساعة 7 عادي
SELECT cron.schedule('andalus-daily-quiz-test-once', '0 20 12 9 *', $$SELECT activate_daily_quiz();$$);

-- 4) تأكيد إن مهمة الـ7 مساءً العادية (اليومية) لسه مسجّلة زي ما هي
SELECT jobid, jobname, schedule, active FROM cron.job WHERE jobname IN ('andalus-daily-quiz-7pm', 'andalus-daily-quiz-test-once');

