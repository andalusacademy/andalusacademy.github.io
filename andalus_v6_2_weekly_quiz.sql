  ON CONFLICT (id) DO NOTHING;

-- 3) الجلسة اليومية — مجموعة الأسئلة المختارة لهذا اليوم بالذات
CREATE TABLE IF NOT EXISTS quiz_daily_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  quiz_date date UNIQUE NOT NULL,
  question_ids jsonb NOT NULL,
  activated_at timestamptz DEFAULT now()
);
ALTER TABLE quiz_daily_sessions DISABLE ROW LEVEL SECURITY;

-- 4) إجابات الطلاب (لكل سؤال فى كل يوم)
CREATE TABLE IF NOT EXISTS quiz_answers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  quiz_date date NOT NULL,
  student_id text NOT NULL,
  question_id uuid NOT NULL,
  selected_option text,
  is_correct boolean,
  points_earned int DEFAULT 0,
  answered_at timestamptz DEFAULT now(),
  UNIQUE(quiz_date, student_id, question_id)
);
ALTER TABLE quiz_answers DISABLE ROW LEVEL SECURITY;

-- 5) النقاط الأسبوعية — مفتاحها (student_id + week_start)، فكل أسبوع جديد بيبدأ صف جديد
--    تلقائيًا (يعني "تصفير" بدون أي عملية يدوية)، والأسابيع القديمة بتفضل محفوظة فى نفس الجدول
CREATE TABLE IF NOT EXISTS quiz_weekly_scores (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id text NOT NULL,
  student_name text,
  week_start date NOT NULL,
  total_points int DEFAULT 0,
  correct_count int DEFAULT 0,
  updated_at timestamptz DEFAULT now(),
  UNIQUE(student_id, week_start)
);
ALTER TABLE quiz_weekly_scores DISABLE ROW LEVEL SECURITY;

