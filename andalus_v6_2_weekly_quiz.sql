-- 1) بنك الأسئلة (منهج أو عام)
CREATE TABLE IF NOT EXISTS quiz_bank_questions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  question text NOT NULL,
  option_a text NOT NULL,
  option_b text NOT NULL,
  option_c text NOT NULL,
  option_d text NOT NULL,
  correct_option text NOT NULL CHECK (correct_option IN ('a','b','c','d')),
  category text,          -- 'منهج' أو 'عام' أو اسم مادة معينة
  points int DEFAULT 10,  -- نقاط السؤال لو اتجاوب صح
  active boolean DEFAULT true,
  created_at timestamptz DEFAULT now()
);
ALTER TABLE quiz_bank_questions DISABLE ROW LEVEL SECURITY;

-- 2) إعدادات المسابقة (صف واحد بس) — الميعاد وعدد الأسئلة قابلين للتغيير من الواجهة مباشرة
CREATE TABLE IF NOT EXISTS quiz_settings (
  id int PRIMARY KEY DEFAULT 1,
  daily_time time DEFAULT '19:00',
  questions_per_day int DEFAULT 5,
  updated_at timestamptz DEFAULT now(),
  CHECK (id = 1)
);
ALTER TABLE quiz_settings DISABLE ROW LEVEL SECURITY;
